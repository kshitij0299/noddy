#!/usr/bin/env node
/**
 * Regenerates server/agent/model-snapshot.js, the offline fallback for the live
 * model list (M4, #76). Only the OpenAI, Anthropic and OpenCode entries of the
 * models.dev catalog are kept, reduced to the fields Noddy shows.
 *
 *   npm run models:snapshot                      fetch https://models.dev/api.json
 *   npm run models:snapshot -- --input api.json  use a saved copy (no network)
 */
import { readFile, rename, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import {
	CATALOG_MAX_BYTES,
	catalogToPlain,
	normalizeCatalog,
	readJsonCapped,
} from '../server/agent/model-catalog.js';
import { CATALOG_URL } from '../server/agent/providers.js';

const args = process.argv.slice(2);
const inputIndex = args.indexOf('--input');
let raw;
if (inputIndex >= 0) {
	if (!args[inputIndex + 1]) throw new Error('--input needs a file path');
	raw = JSON.parse(await readFile(args[inputIndex + 1], 'utf8'));
} else {
	const response = await fetch(CATALOG_URL, {
		redirect: 'error',
		signal: AbortSignal.timeout(30000),
	});
	if (!response.ok) throw new Error(`models.dev answered ${response.status}`);
	raw = await readJsonCapped(response, CATALOG_MAX_BYTES);
}

// Throws on a missing or empty provider, so a broken download never overwrites the snapshot.
const plain = catalogToPlain(normalizeCatalog(raw));
const today = new Date().toISOString().slice(0, 10);

const lines = [
	`// Generated by scripts/build-model-snapshot.mjs from ${CATALOG_URL} on ${today}.`,
	'// Do not edit by hand: run `npm run models:snapshot`. Only OpenAI, Anthropic and OpenCode entries.',
	'// Fallback for the live model list when models.dev cannot be reached (see model-catalog.js).',
	'export const MODEL_SNAPSHOT = {',
	`\tgenerated: '${today}',`,
	`\tsource: '${CATALOG_URL}',`,
	'\tproviders: {',
];
for (const [provider, models] of Object.entries(plain)) {
	lines.push(`\t\t${JSON.stringify(provider)}: {`);
	for (const id of Object.keys(models).sort()) {
		lines.push(`\t\t\t${JSON.stringify(id)}: ${JSON.stringify(models[id])},`);
	}
	lines.push('\t\t},');
}
lines.push('\t},', '};', '');

const target = fileURLToPath(new URL('../server/agent/model-snapshot.js', import.meta.url));
await writeFile(`${target}.tmp`, lines.join('\n'));
await rename(`${target}.tmp`, target);
console.info(
	`Wrote ${target} (${Object.entries(plain)
		.map(([provider, models]) => `${provider}: ${Object.keys(models).length}`)
		.join(', ')})`
);
